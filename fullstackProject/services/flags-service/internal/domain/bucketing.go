package domain

import "hash/fnv"

// Bucket — детерминированный бакет сущности в раскатке флага:
// FNV-1a 64 по строке "key|entityID", остаток на 100. Без зависимости
// и без состояния — одинаковая пара (флаг, сущность) даёт один бакет
// на любом инстансе сервиса.
//
// Алгоритм ЗЕРКАЛЕН TS-стороне (apps/api/src/flags): API кэширует
// снимки флагов и считает вердикты локально тем же правилом, чтобы
// kill-switch вступал в силу за TTL кэша, а не за походом за каждым
// вердиктом. Векторы-константы зафиксированы тестами с обеих сторон:
// дрейф реализации ломает тест, а не раскатку.
func Bucket(key, entityID string) int {
	h := fnv.New64a()
	_, _ = h.Write([]byte(key))
	_, _ = h.Write([]byte{'|'})
	_, _ = h.Write([]byte(entityID))
	return int(h.Sum64() % 100)
}
